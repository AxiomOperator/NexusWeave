pub const MAX_FILE_SIZE: u64 = 1_500_000;

const DEFAULT_EXCLUDES: &[&str] = &[
    "node_modules", "vendor", "dist", "build", "target", "out", ".git", "__pycache__", ".venv", "venv",
    "env", ".tox", "coverage", ".next", ".nuxt", ".svelte-kit", ".turbo", ".cache", "bower_components",
    "Pods", "DerivedData", ".gradle", "bin", "obj", ".xgraph", ".codegraph", "site-packages", ".mypy_cache",
    ".pytest_cache",
];

#[derive(Debug, Clone)]
pub struct Candidate {
    pub rel: String,
    pub abs: PathBuf,
    pub lang: Lang,
    pub size: u64,
    pub mtime: i64,
}

#[derive(Debug, Default, Clone, serde::Serialize)]
pub struct Stats {
    pub files_scanned: usize,
    pub files_indexed: usize,
    pub files_removed: usize,
    pub files_unchanged: usize,
    pub nodes: usize,
    pub refs: usize,
    pub resolved: usize,
    pub ms_discover: u128,
    pub ms_parse: u128,
    pub ms_resolve: u128,
    pub ms_total: u128,
}

pub fn is_test_path(p: &str) -> bool {
    let lower = p.to_ascii_lowercase();
    let file = lower.rsplit('/').next().unwrap_or(&lower);
    lower.split('/').any(|seg| matches!(seg, "test" | "tests" | "__tests__" | "spec" | "specs" | "testing" | "e2e" | "__mocks__" | "fixtures" | "testdata"))
        || file.contains(".test.") || file.contains(".spec.") || file.ends_with("_test.go") || file.ends_with("_test.py")
        || file.starts_with("test_") || file.ends_with("_spec.rb") || file.ends_with("_test.rb")
        || file.ends_with("test.java") || file.ends_with("tests.java") || file.ends_with("tests.cs") || file.ends_with("test.cs")
        || file.ends_with("test.php") || file.ends_with("_test.cc") || file.ends_with("_test.cpp") || file.ends_with("_tests.rs")
        || file == "conftest.py"
}

fn is_generated(path: &str, src: &[u8]) -> bool {
    let f = path.rsplit('/').next().unwrap_or(path);
    if f.ends_with(".pb.go") || f.ends_with(".pb.cc") || f.ends_with(".pb.h") || f.contains(".generated.") || f.ends_with(".g.cs")
        || f.ends_with(".designer.cs") || f.ends_with("_pb2.py") || f.ends_with(".min.js") || f.ends_with(".d.ts") && f.contains("generated")
        || f.ends_with("_generated.go") || f.ends_with("_generated.rs") { return true; }
    let head = &src[..src.len().min(600)];
    let head = String::from_utf8_lossy(head);
    head.contains("Code generated") || head.contains("@generated") || head.contains("DO NOT EDIT") || head.contains("<auto-generated")
}

fn minified(src: &[u8]) -> bool {
    if src.len() < 20_000 { return false; }
    let lines = src.iter().filter(|&&b| b == b'\n').count().max(1);
    src.len() / lines > 400
}

/// Whether a project-relative path is excluded by default dirs or root-level ignore files.
pub fn excluded(root: &Path, rel: &str) -> bool {
    let mut segs: Vec<&str> = rel.split('/').collect();
    segs.pop();
    if segs.iter().any(|s| DEFAULT_EXCLUDES.contains(s) || s.starts_with('.')) { return true; }
    let mut b = ignore::gitignore::GitignoreBuilder::new(root);
    let mut dir = root.to_path_buf();
    for f in [".gitignore", ".xgraphignore"] { let _ = b.add(dir.join(f)); }
    for s in &segs {
        dir = dir.join(s);
        for f in [".gitignore", ".xgraphignore"] { let p = dir.join(f); if p.exists() { let _ = b.add(p); } }
    }
    match b.build() {
        Ok(gi) => gi.matched_path_or_any_parents(rel, false).is_ignore(),
        Err(_) => false,
    }
}

pub fn discover(root: &Path) -> Vec<Candidate> {
    let mut wb = ignore::WalkBuilder::new(root);
    wb.hidden(true).git_ignore(true).git_global(false).git_exclude(true).parents(false)
        .add_custom_ignore_filename(".xgraphignore").follow_links(false)
        .threads(std::thread::available_parallelism().map(|n| n.get()).unwrap_or(4).min(12));
    let root_owned = root.to_path_buf();
    wb.filter_entry(move |e| {
        if e.depth() == 0 { return true; }
        let name = e.file_name().to_string_lossy();
        if e.file_type().is_some_and(|t| t.is_dir()) {
            return !DEFAULT_EXCLUDES.contains(&name.as_ref());
        }
        true
    });
    let out = Mutex::new(Vec::new());
    wb.build_parallel().run(|| {
        let out = &out;
        let root = &root_owned;
        Box::new(move |res| {
            let Ok(e) = res else { return ignore::WalkState::Continue };
            if !e.file_type().is_some_and(|t| t.is_file()) { return ignore::WalkState::Continue; }
            let p = e.path();
            let Ok(rel) = p.strip_prefix(root) else { return ignore::WalkState::Continue };
            let rel = rel.to_string_lossy().replace('\\', "/");
            let Some(lang) = Lang::from_path(&rel) else { return ignore::WalkState::Continue };
            let Ok(md) = e.metadata() else { return ignore::WalkState::Continue };
            if md.len() > MAX_FILE_SIZE || md.len() == 0 { return ignore::WalkState::Continue; }
            let mtime = md.modified().ok().and_then(|t| t.duration_since(UNIX_EPOCH).ok()).map(|d| d.as_millis() as i64).unwrap_or(0);
            out.lock().unwrap().push(Candidate { rel, abs: p.to_path_buf(), lang, size: md.len(), mtime });
            ignore::WalkState::Continue
        })
    });
    let mut v = out.into_inner().unwrap();
    v.sort_by(|a, b| a.rel.cmp(&b.rel));
    v
}

pub struct Parsed {
    pub meta: FileMeta,
    pub ex: FileExtraction,
}

pub fn parse_file(c: &Candidate) -> Option<Parsed> {
    let src = std::fs::read(&c.abs).ok()?;
    let hash = xxhash_rust::xxh3::xxh3_64(&src);
    Some(parse_bytes(c, &src, hash))
}

fn parse_bytes(c: &Candidate, src: &[u8], hash: u64) -> Parsed {
    let generated = is_generated(&c.rel, src);
    let ex = if minified(src) { FileExtraction::default() } else { crate::extract::extract(c.lang, &c.rel, src) };
    Parsed {
        meta: FileMeta { path: c.rel.clone(), lang: c.lang, hash, size: c.size, mtime: c.mtime, is_test: is_test_path(&c.rel), generated },
        ex,
    }
}

fn pool() -> &'static rayon::ThreadPool {
    static POOL: std::sync::OnceLock<rayon::ThreadPool> = std::sync::OnceLock::new();
    POOL.get_or_init(|| rayon::ThreadPoolBuilder::new().stack_size(32 << 20).thread_name(|i| format!("xgraph-parse-{i}")).build().unwrap())
}

/// Parse candidates in parallel and stream results into `sink` on the calling thread, in
/// candidate (sorted path) order — ids, and therefore every tie-break, are reproducible.
fn parse_stream(cands: Vec<Candidate>, mut sink: impl FnMut(Parsed) -> Result<()>) -> Result<()> {
    let (tx, rx) = crossbeam_channel::bounded::<(usize, Option<Parsed>)>(1024);
    let next_job = std::sync::atomic::AtomicUsize::new(0);
    let workers = std::thread::available_parallelism().map(|n| n.get()).unwrap_or(4);
    std::thread::scope(|s| {
        // workers claim files in index order, so in-order writing never waits on one thread's backlog
        for w in 0..workers {
            let (tx, cands, next_job) = (tx.clone(), &cands, &next_job);
            std::thread::Builder::new().name(format!("xgraph-parse-{w}")).stack_size(32 << 20).spawn_scoped(s, move || {
                loop {
                    let i = next_job.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                    let Some(c) = cands.get(i) else { break };
                    if tx.send((i, parse_file(c))).is_err() { break; }
                }
            }).expect("spawn parser thread");
        }
        drop(tx);
        let mut pending: std::collections::BTreeMap<usize, Option<Parsed>> = std::collections::BTreeMap::new();
        let mut next = 0;
        for (i, p) in rx {
            pending.insert(i, p);
            while let Some(p) = pending.remove(&next) {
                if let Some(p) = p { sink(p)?; }
                next += 1;
            }
        }
        Ok(())
    })
}

pub fn ensure_dir(root: &Path) -> Result<()> {
    let d = root.join(".xgraph");
    std::fs::create_dir_all(&d)?;
    let gi = d.join(".gitignore");
    if !gi.exists() { std::fs::write(gi, "*\n")?; }
    Ok(())
}

/// Build the graph from scratch.
pub fn full_index(root: &Path, mut progress: impl FnMut(usize, usize)) -> Result<Stats> {
    let t0 = Instant::now();
    ensure_dir(root)?;
    let path = db_path(root);
    // Build into a temp file, then atomically swap: readers keep a consistent graph meanwhile.
    let tmp = path.with_extension("db.building");
    for ext in ["", "-wal", "-shm"] { let _ = std::fs::remove_file(format!("{}{ext}", tmp.display())); }
    let mut db = Db::open(&tmp)?;
    db.conn.execute_batch("PRAGMA synchronous=OFF; PRAGMA foreign_keys=OFF; PRAGMA journal_mode=OFF; PRAGMA threads=8; PRAGMA cache_size=-262144;")?;
    db.drop_indexes()?;
    let mut st = Stats::default();
    let cands = discover(root);
    st.files_scanned = cands.len();
    st.ms_discover = t0.elapsed().as_millis();
    let t1 = Instant::now();
    let total = cands.len();
    let mut pending: Vec<crate::db::PendingRef> = Vec::new();
    {
        let mut w = Writer::new(&mut db)?;
        let mut done = 0;
        let mut busy = std::time::Duration::ZERO;
        let pending = &mut pending;
        parse_stream(cands, |p| {
            st.nodes += p.ex.nodes.len();
            st.refs += p.ex.refs.len();
            let t = Instant::now();
            w.insert_with(&p.meta, &p.ex, Some(pending))?;
            busy += t.elapsed();
            done += 1;
            if done % 200 == 0 || done == total { progress(done, total); }
            Ok(())
        })?;
        let t = Instant::now();
        w.commit()?;
        if std::env::var_os("XGRAPH_TRACE").is_some() { eprintln!("[index] writer busy {} ms, commit {} ms", busy.as_millis(), t.elapsed().as_millis()); }
    }
    st.files_indexed = total;
    st.ms_parse = t1.elapsed().as_millis();
    let t2 = Instant::now();
    st.resolved = crate::resolve::resolve(&mut db, root, crate::resolve::Scope::Fresh(pending))?;
    let t = Instant::now();
    db.create_indexes()?;
    if std::env::var_os("XGRAPH_TRACE").is_some() { eprintln!("[index] create indexes {} ms", t.elapsed().as_millis()); }
    st.ms_resolve = t2.elapsed().as_millis();
    db.set_meta("indexed_at", &now_ms().to_string())?;
    db.set_meta("version", env!("CARGO_PKG_VERSION"))?;
    let t = Instant::now();
    db.conn.execute_batch("INSERT INTO nodes_fts(nodes_fts) VALUES('optimize');")?;
    let t_opt = t.elapsed();
    let t = Instant::now();
    // sampled statistics: the planner only needs rough row counts per index
    db.conn.execute_batch("PRAGMA journal_mode=WAL; PRAGMA analysis_limit=1000; ANALYZE;")?;
    if std::env::var_os("XGRAPH_TRACE").is_some() { eprintln!("[index] fts optimize {} ms, analyze {} ms", t_opt.as_millis(), t.elapsed().as_millis()); }
    drop(db);
    for ext in ["-wal", "-shm"] { let _ = std::fs::remove_file(format!("{}{ext}", path.display())); }
    std::fs::rename(&tmp, &path)?;
    st.ms_total = t0.elapsed().as_millis();
    Ok(st)
}

/// Re-resolve every reference (after module configuration or stub changes).
pub fn reresolve(root: &Path) -> Result<Stats> {
    let t0 = Instant::now();
    let mut db = Db::open(&db_path(root))?;
    db.ensure_sync_indexes()?;
    let mut st = Stats { resolved: crate::resolve::resolve(&mut db, root, crate::resolve::Scope::All)?, ..Default::default() };
    st.ms_resolve = t0.elapsed().as_millis();
    st.ms_total = st.ms_resolve;
    Ok(st)
}

pub fn now_ms() -> i64 {
    std::time::SystemTime::now().duration_since(UNIX_EPOCH).map(|d| d.as_millis() as i64).unwrap_or(0)
}

struct Known { id: i64, hash: u64, size: u64, mtime: i64 }

/// Incremental update. `only` restricts the scan to specific project-relative paths (from the watcher);
/// `None` reconciles the whole tree.
pub fn sync(root: &Path, only: Option<&[String]>) -> Result<Stats> { sync_with(root, only, None) }

/// Incremental update that reuses resolver state across calls (see [`crate::resolve::Cache`]).
pub fn sync_with(root: &Path, only: Option<&[String]>, mut cache: Option<&mut Option<crate::resolve::Cache>>) -> Result<Stats> {
    let t0 = Instant::now();
    let path = db_path(root);
    let rebuild = |cache: &mut Option<&mut Option<crate::resolve::Cache>>| {
        if let Some(c) = cache.as_mut() { **c = None; }
        full_index(root, |_, _| {})
    };
    if !path.exists() { return rebuild(&mut cache); }
    let mut db = Db::open(&path)?;
    if !db.compatible() {
        drop(db);
        return rebuild(&mut cache);
    }
    db.ensure_sync_indexes()?;
    let mut st = Stats::default();
    let mut known: HashMap<String, Known> = HashMap::new();
    {
        let mut q = db.conn.prepare("SELECT id, path, hash, size, mtime FROM files")?;
        let rows = q.query_map([], |r| Ok((r.get::<_, String>(1)?, Known { id: r.get(0)?, hash: r.get::<_, i64>(2)? as u64, size: r.get::<_, i64>(3)? as u64, mtime: r.get(4)? })))?;
        for row in rows { let (p, k) = row?; known.insert(p, k); }
    }
    let cands: Vec<Candidate> = match only {
        None => discover(root),
        Some(paths) => paths.iter().filter_map(|rel| {
            if excluded(root, rel) { return None; }
            let abs = root.join(rel);
            let lang = Lang::from_path(rel)?;
            let md = std::fs::metadata(&abs).ok()?;
            if !md.is_file() || md.len() > MAX_FILE_SIZE || md.len() == 0 { return None; }
            let mtime = md.modified().ok().and_then(|t| t.duration_since(UNIX_EPOCH).ok()).map(|d| d.as_millis() as i64).unwrap_or(0);
            Some(Candidate { rel: rel.clone(), abs, lang, size: md.len(), mtime })
        }).collect(),
    };
    st.files_scanned = cands.len();
    st.ms_discover = t0.elapsed().as_millis();
    let t1 = Instant::now();

    let present: HashSet<&str> = cands.iter().map(|c| c.rel.as_str()).collect();
    let removed: Vec<i64> = match only {
        None => known.iter().filter(|(p, _)| !present.contains(p.as_str())).map(|(_, k)| k.id).collect(),
        Some(paths) => paths.iter().filter(|p| !present.contains(p.as_str())).filter_map(|p| known.get(p).map(|k| k.id)).collect(),
    };
    // Cheap pre-filter on size+mtime, then confirm by content hash.
    let maybe: Vec<&Candidate> = cands.iter().filter(|c| match known.get(&c.rel) {
        Some(k) => k.size != c.size || k.mtime != c.mtime,
        None => true,
    }).collect();
    let results: Vec<(Option<i64>, Option<Parsed>, i64)> = pool().install(|| maybe.par_iter().filter_map(|c| {
        let src = std::fs::read(&c.abs).ok()?;
        let hash = xxhash_rust::xxh3::xxh3_64(&src);
        match known.get(&c.rel) {
            Some(k) if k.hash == hash => Some((Some(k.id), None, c.mtime)),
            k => Some((k.map(|k| k.id), Some(parse_bytes(c, &src, hash)), c.mtime)),
        }
    }).collect());
    st.files_unchanged = cands.len() - results.iter().filter(|r| r.1.is_some()).count();

    let changed_ids: Vec<i64> = results.iter().filter(|r| r.1.is_some()).filter_map(|r| r.0).chain(removed.iter().copied()).collect();
    if changed_ids.is_empty() && results.iter().all(|r| r.1.is_none()) {
        if !results.is_empty() {
            let w = Writer::new(&mut db)?;
            for (id, _, m) in &results { if let Some(id) = id { w.touch(*id, *m)?; } }
            w.commit()?;
        }
        st.ms_total = t0.elapsed().as_millis();
        return Ok(st);
    }
    // Names defined by files about to be replaced: refs elsewhere that point at (or could now point at) them need re-resolution.
    let mut affected_names: HashSet<String> = HashSet::new();
    {
        let mut q = db.conn.prepare_cached("SELECT name FROM nodes WHERE file_id=? AND kind != 0")?;
        for id in &changed_ids {
            for n in q.query_map([id], |r| r.get::<_, String>(0))? { affected_names.insert(n?); }
        }
    }
    // Import bindings that currently resolve into the files being replaced, following re-export
    // chains (barrels): refs spelled with those local names must be re-resolved afterwards.
    let mut aliases: Vec<(i64, String)> = Vec::new();
    {
        let mut reach: HashSet<i64> = changed_ids.iter().copied().collect();
        let mut frontier: Vec<i64> = changed_ids.clone();
        let mut q = db.conn.prepare_cached("SELECT file_id, local, kind FROM imports WHERE target_file = ?")?;
        for _ in 0..8 {
            let mut next = Vec::new();
            for t in &frontier {
                for r in q.query_map([t], |r| Ok((r.get::<_, i64>(0)?, r.get::<_, String>(1)?, r.get::<_, i64>(2)?)))? {
                    let (f, local, kind) = r?;
                    if !local.is_empty() { aliases.push((f, local)); }
                    let k = ImportKind::from_i64(kind);
                    if matches!(k, ImportKind::ReExport | ImportKind::ReExportAll) && reach.insert(f) { next.push(f); }
                }
            }
            if next.is_empty() { break; }
            frontier = next;
        }
        aliases.sort();
        aliases.dedup();
    }
    let mut via_refs: Vec<i64> = Vec::new();
    {
        let mut q = db.conn.prepare_cached("SELECT r.id FROM nodes n JOIN refs r ON r.via_id = n.id WHERE n.file_id = ?")?;
        for f in &changed_ids { for r in q.query_map([f], |r| r.get(0))? { via_refs.push(r?); } }
    }
    let mut new_file_ids = Vec::new();
    {
        let mut w = Writer::new(&mut db)?;
        for id in &changed_ids { w.delete_file(*id)?; }
        for (id, parsed, m) in &results {
            match parsed {
                None => { if let Some(id) = id { w.touch(*id, *m)?; } }
                Some(p) => {
                    for n in &p.ex.nodes { if n.kind != NodeKind::File { affected_names.insert(n.name.clone()); } }
                    st.nodes += p.ex.nodes.len();
                    st.refs += p.ex.refs.len();
                    new_file_ids.push(w.insert(&p.meta, &p.ex)?);
                }
            }
        }
        w.commit()?;
    }
    st.files_indexed = new_file_ids.len();
    st.files_removed = removed.len();
    st.ms_parse = t1.elapsed().as_millis();
    let t2 = Instant::now();
    st.resolved = crate::resolve::resolve_with(&mut db, root, crate::resolve::Scope::Incremental {
        files: new_file_ids, names: affected_names.into_iter().collect(), removed: changed_ids, aliases, via_refs,
    }, cache)?;
    st.ms_resolve = t2.elapsed().as_millis();
    db.set_meta("indexed_at", &now_ms().to_string())?;
    st.ms_total = t0.elapsed().as_millis();
    Ok(st)
}
